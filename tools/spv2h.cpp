#include <cstdint>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

// Simple SPIR-V to C header converter
// Usage: spv2h <input.spv> [output.h] [symbolName]
// Defaults: output to stdout if not provided; symbolName defaults to kComputeShaderSpv

static void printUsage(const char* exe) {
    std::cerr << "Usage: " << exe << " <input.spv> [output.h] [symbolName]\n";
}

int main(int argc, char** argv) {
    if (argc < 2) { printUsage(argv[0]); return 1; }
    std::string inPath = argv[1];
    std::string outPath = (argc >= 3 ? argv[2] : "-");
    std::string symbol = (argc >= 4 ? argv[3] : "kComputeShaderSpv");

    std::ifstream in(inPath, std::ios::binary);
    if (!in) {
        std::cerr << "Error: cannot open input file: " << inPath << "\n";
        return 1;
    }
    std::vector<uint8_t> bytes((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    if (bytes.empty()) {
        std::cerr << "Error: input file is empty\n";
        return 1;
    }
    if (bytes.size() % 4 != 0) {
        std::cerr << "Error: SPIR-V file size is not a multiple of 4 bytes\n";
        return 1;
    }

    const uint32_t* words = reinterpret_cast<const uint32_t*>(bytes.data());
    size_t wordCount = bytes.size() / 4;

    std::ostream* out = &std::cout;
    std::ofstream outFile;
    if (outPath != "-") {
        outFile.open(outPath, std::ios::binary);
        if (!outFile) {
            std::cerr << "Error: cannot open output file: " << outPath << "\n";
            return 1;
        }
        out = &outFile;
    }

    (*out) << "#pragma once\n\n";
    (*out) << "#include <cstdint>\n\n";
    (*out) << "// Generated by spv2h. Do not edit manually.\n";
    (*out) << "static const uint32_t " << symbol << "[] = {\n";

    const size_t kPerLine = 8;
    for (size_t i = 0; i < wordCount; ++i) {
        if (i % kPerLine == 0) (*out) << "    ";
        // print as 0xXXXXXXXXu
        (*out) << "0x" << std::hex;
        (*out).width(8);
        (*out).fill('0');
        (*out) << words[i] << std::dec << "u";
        if (i + 1 != wordCount) (*out) << ", ";
        if (i % kPerLine == kPerLine - 1 || i + 1 == wordCount) (*out) << "\n";
    }
    (*out) << "};\n\n";
    (*out) << "static constexpr size_t " << symbol << "Size = sizeof(" << symbol << ");\n";

    return 0;
}


